out.push('-- ---------------------------- customers -------------------------');
const seen = new Set();
for (const [, name, email, phone, city] of BOOKINGS) {
  if (seen.has(name)) continue;
  seen.add(name);
  out.push(`INSERT IGNORE INTO customers (full_name, email, phone, city)`);
  out.push(`  VALUES (${q(name)}, ${q(email)}, ${q(phone)}, ${q(city)});`);
}
out.push('');

out.push('-- ---------------------------- bookings --------------------------');
out.push('-- day_rate and total are computed from the vehicle at seed time,');
out.push('-- then stored, so a later price edit cannot rewrite history.');
for (const [ref, name, , , , slug, from, to, status] of BOOKINGS) {
  out.push(`INSERT IGNORE INTO bookings`);
  out.push(`  (reference, customer_id, vehicle_id, starts_on, ends_on, status, day_rate, total)`);
  out.push(`SELECT ${q(ref)}, c.id, v.id, ${q(from)}, ${q(to)}, ${q(status)},`);
  out.push(`       v.price,`);
  out.push(`       CASE WHEN v.listing_type = 'rental'`);
  out.push(`            THEN v.price * GREATEST(DATEDIFF(${q(to)}, ${q(from)}), 1)`);
  out.push(`            ELSE v.price END`);
  out.push(`  FROM customers c, vehicles v`);
  out.push(` WHERE c.full_name = ${q(name)} AND v.slug = ${q(slug)};`);
  out.push('');
}

const dest = path.join(__dirname, 'seed.sql');
fs.writeFileSync(dest, out.join('\n'), 'utf8');

const features = CARS.reduce((n, c) => n + (c.features || []).length, 0);
