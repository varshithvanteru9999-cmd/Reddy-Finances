/* ---- the sample people, in a file of their own ---- */
const sample = [
  '-- Sample customers and bookings — INVENTED PEOPLE, for local work.',
  '--',
  '-- Never run this against a live database. db/setup.js does not touch',
  '-- it; load it by hand when you want something on the screen:',
  '--     mysql -u root -p reddy_finances < db/seed-sample.sql',
  '--',
  '-- Generated by db/make-seed.js — do not hand-edit.',
  '',
  'USE reddy_finances;',
  'SET NAMES utf8mb4;',
  '',
  '-- ---------------------------- customers -------------------------'
];

const seen = new Set();
for (const [, name, email, phone, city] of BOOKINGS) {
  if (seen.has(name)) continue;
  seen.add(name);
  sample.push(`INSERT IGNORE INTO customers (full_name, email, phone, city)`);
  sample.push(`  VALUES (${q(name)}, ${q(email)}, ${q(phone)}, ${q(city)});`);
}
sample.push('');

sample.push('-- ---------------------------- bookings --------------------------');
sample.push('-- day_rate and total are computed from the vehicle at seed time,');
sample.push('-- then stored, so a later price edit cannot rewrite history.');
for (const [ref, name, , , , slug, from, to, status] of BOOKINGS) {
  sample.push(`INSERT IGNORE INTO bookings`);
  sample.push(`  (reference, customer_id, vehicle_id, starts_on, ends_on, status, day_rate, total)`);
  sample.push(`SELECT ${q(ref)}, c.id, v.id, ${q(from)}, ${q(to)}, ${q(status)},`);
  sample.push(`       v.price,`);
  sample.push(`       CASE WHEN v.listing_type = 'rental'`);
  sample.push(`            THEN v.price * GREATEST(DATEDIFF(${q(to)}, ${q(from)}), 1)`);
  sample.push(`            ELSE v.price END`);
  sample.push(`  FROM customers c, vehicles v`);
  sample.push(` WHERE c.full_name = ${q(name)} AND v.slug = ${q(slug)};`);
  sample.push('');
}

const sampleDest = path.join(__dirname, 'seed-sample.sql');
fs.writeFileSync(sampleDest, sample.join('\n'), 'utf8');

