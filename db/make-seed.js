/* ------------------------------------------------------------------
   Generates db/seed.sql from js/data.js, so the database seed and the
   front-end seed can never drift apart. Re-run after editing data.js:

     node db/make-seed.js
------------------------------------------------------------------- */

const fs = require('fs');
const path = require('path');

/* data.js declares `const CARS` for a browser <script>, so requiring it
   exposes nothing. Read and evaluate it to get the array out. */
const CARS = (() => {
  const src = fs.readFileSync(path.join(__dirname, '..', 'js', 'data.js'), 'utf8');
  return new Function(`${src}; return CARS;`)();
})();

/* MySQL string literal: escape backslash and single quote. */
function q(value) {
  if (value === null || value === undefined || value === '') return 'NULL';
  const escaped = String(value)
    .split('\\').join('\\\\')
    .split("'").join("''");
  return `'${escaped}'`;
}

const out = [
  'USE reddy_finances;',
  'SET NAMES utf8mb4;',
  '',
  '-- Generated by db/make-seed.js from js/data.js — do not hand-edit.',
  '-- Re-running is safe: vehicles upsert, features and bookings are',
  '-- INSERT IGNORE against unique keys.',
  ''
];

/* ------------------------------ vehicles -------------------------- */

for (const c of CARS) {
  const cols = [
    'slug', 'listing_type', 'name', 'trim_level', 'model_year', 'price', 'body',
    'seats', 'doors', 'transmission', 'fuel', 'economy', 'drivetrain', 'engine',
    'power', 'top_speed', 'zero_to_sixty', 'color', 'mileage', 'location',
    'image_path', 'description'
  ];
  const vals = [
    q(c.id), q(c.type), q(c.name), q(c.trim), c.year, c.price, q(c.body),
    c.seats, c.doors, q(c.transmission), q(c.fuel), q(c.economy), q(c.drivetrain),
    q(c.engine), q(c.power), q(c.topSpeed), q(c.zeroToSixty), q(c.color),
    q(c.mileage), q(c.location), q(c.image), q(c.description)
  ];

  out.push(`INSERT INTO vehicles (${cols.join(', ')}) VALUES`);
  out.push(`  (${vals.join(', ')})`);
  out.push('  ON DUPLICATE KEY UPDATE');
  out.push('    name = VALUES(name), trim_level = VALUES(trim_level),');
  out.push('    price = VALUES(price), location = VALUES(location),');
  out.push('    image_path = VALUES(image_path), updated_at = CURRENT_TIMESTAMP;');

  for (const f of c.features || []) {
    out.push(`INSERT IGNORE INTO vehicle_features (vehicle_id, feature)`);
    out.push(`  SELECT id, ${q(f)} FROM vehicles WHERE slug = ${q(c.id)};`);
  }
  out.push('');
}

